function numericMath() {
	let checksum = 0;
	for (let index = 0; index < 65536; index++) {
		const value = (index % 10000) / 64 - 70;
		checksum =
			(checksum +
				Math.round(value) +
				Math.floor(value) +
				Math.ceil(value) +
				Math.trunc(value) +
				Math.abs(value) +
				Math.sqrt(value * value) +
				Math.sign(value) +
				Math.fround(value) +
				Math.min(value, 32) +
				Math.max(value, -32)) %
			1000000007;
	}
	return checksum;
}
