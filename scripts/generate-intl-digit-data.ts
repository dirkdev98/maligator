import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const revision = "7d2b9cb11cec08f4d333ad73209deb3df0711c3b";
const digest = "4ad27e2439638ffb5344772c8d3dc8502c94f3c898b9bf9ce1a2fe092ce082d8";
const [input, output] = process.argv.slice(2);
if (input === undefined || output === undefined) {
	throw new Error(
		"Usage: node scripts/generate-intl-digit-data.ts <numberingSystems.json> <output.rs>",
	);
}
const bytes = readFileSync(input);
if (createHash("sha256").update(bytes).digest("hex") !== digest) {
	throw new Error("CLDR numbering-system source checksum mismatch");
}
const source = JSON.parse(bytes.toString("utf8")) as {
	supplemental: { numberingSystems: Record<string, { _type: string; _digits?: string }> };
};
const entries = Object.entries(source.supplemental.numberingSystems)
	.filter(([, system]) => system._type === "numeric")
	.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
	.map(([name, system]) => {
		const digits = [...(system._digits ?? "")];
		if (
			!/^[a-z0-9]{3,8}$/.test(name) ||
			digits.length !== 10 ||
			new Set(digits).size !== 10
		) {
			throw new Error(`Invalid decimal digit system: ${name}`);
		}
		return `    ("${name}", [${digits.map((digit) => `'\\u{${digit.codePointAt(0)!.toString(16)}}'`).join(", ")}]),`;
	});
const text = [
	"// Generated by scripts/generate-intl-digit-data.ts; do not edit.",
	`// CLDR ${revision}, supplemental/numberingSystems.json, SHA256 ${digest}.`,
	"// Unicode-3.0; see runtime/vendor/cldr/LICENSE and THIRD_PARTY_NOTICES.md.",
	"#[rustfmt::skip]",
	"pub(super) static DIGITS: &[(&str, [char; 10])] = &[",
	...entries,
	"];",
	"",
].join("\n");
mkdirSync(dirname(resolve(output)), { recursive: true });
writeFileSync(output, text);
console.log(resolve(output));
