export type BytecodeOperation = (typeof BYTECODE_OPERATIONS)[number];

export function generateBytecodeOperationInclude(): string {
	return [
		"/* Generated by scripts/generate-bytecode-operations.ts. Do not edit. */",
		"/* BYTECODE_OPERATION(name) expands in canonical wire/runtime ordinal order. */",
		`#define MAL_PRECISE_NUMBER_SUM_MAX_INPUTS ${MAX_PRECISE_NUMBER_SUM_INPUTS}`,
		...BYTECODE_OPERATIONS.map((operation) => `BYTECODE_OPERATION(${operation})`),
		"",
	].join("\n");
}
