const prefix = "mal_host_install_node_";
const reasons = new Map<string, ReadonlyMap<string, string>>();
for (const [module, reason, ...names] of moduleGroups) {
	const group = new Map(reasons.get(module));
	for (const name of names) group.set(name, reason);
	reasons.set(module, group);
}

export function hostModuleInvocationUnavailable(
	installer: string,
	name: string,
): string | undefined {
	if (installer === "mal_host_install_process") return reasons.get("process")?.get(name);
	if (!installer.startsWith(prefix)) return undefined;
	const module = installer.slice(prefix.length);
	return reasons.get(aliases.get(module) ?? module)?.get(name);
}

