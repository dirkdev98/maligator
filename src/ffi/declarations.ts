import { artifactDigest } from "../artifact-store.ts";
import type { BindingPlan, MappedConstant } from "./binding-plan.ts";
import { ffiModuleSpecifier } from "./binding-unit.ts";
import { formatTsParameters, formatTsResult, formatTsType } from "./inspect.ts";

function docComment(doc: string | undefined, indent: string): Array<string> {
	if (doc === undefined) return [];
	const lines = doc.replaceAll("*/", "*\\/").split("\n");
	return lines.length === 1
		? [`${indent}/** ${lines[0]} */`]
		: [
				`${indent}/**`,
				...lines.map((line) => `${indent} * ${line}`.trimEnd()),
				`${indent} */`,
			];
}

/** A literal type for a constant whose value the build already knows. */
function constantType(constant: MappedConstant): string {
	const known = constant.known;
	if (typeof known === "bigint") return `${known}n`;
	if (typeof known === "string") return JSON.stringify(known);
	if (typeof known === "number" && Number.isInteger(known)) return String(known);
	return formatTsType(constant.value);
}

function moduleDeclaration(library: string, plan: BindingPlan): Array<string> {
	const lines = [`declare module ${JSON.stringify(ffiModuleSpecifier(library))} {`];
	if (plan.handles.size > 0) lines.push("\tconst maligatorFfiHandle: unique symbol;");
	const records = [...plan.records.values()].sort((left, right) =>
		left.name < right.name ? -1 : left.name > right.name ? 1 : 0,
	);
	for (const record of records) {
		lines.push(
			...docComment(record.record.doc, "\t"),
			`\texport interface ${record.name} {`,
		);
		for (const field of record.fields) {
			lines.push(
				...docComment(field.doc, "\t\t"),
				`\t\t${field.name}: ${formatTsType(field.value)};`,
			);
		}
		lines.push("\t}");
	}
	for (const handle of plan.handles.values()) {
		const fields = [
			...handle.fields.flatMap((field) => [
				...docComment(field.doc, "\t\t"),
				`\t\treadonly ${field.name}: ${formatTsType(field.value)};`,
			]),
			...handle.managedFields.flatMap((field) => [
				...docComment(field.doc, "\t\t"),
				`\t\tget ${field.name}(): Uint8Array | null;`,
				`\t\tset ${field.name}(value: ArrayBuffer | ArrayBufferView | null);`,
			]),
		];
		lines.push(
			...docComment(handle.doc, "\t"),
			`\texport interface ${handle.name} {`,
			`\t\treadonly [maligatorFfiHandle]: { ${[handle.name, ...handle.views].map((name) => `readonly ${name}: true`).join("; ")} };`,
			"\t\treadonly [Symbol.toStringTag]: string;",
			`\t\t/** Close the handle${handle.destroy === undefined ? "" : `, releasing an owned resource with ${handle.destroy.name}`}.${handle.destroy?.success === undefined ? "" : " Failed C cleanup throws and leaves it open for retry."} */`,
			"\t\t[Symbol.dispose](): void;",
		);
		// A canonical pointer view keeps its original prototype; only the factory guarantees accessors.
		if (handle.allocator === undefined) lines.push(...fields);
		lines.push("\t}");
		if (handle.allocator !== undefined)
			lines.push(
				"\t/** Allocate zeroed caller storage. C initialization and cleanup remain explicit. */",
				`\texport function ${handle.allocator}(): ${handle.name}${fields.length === 0 ? ";" : " & {"}`,
				...(fields.length === 0 ? [] : [...fields, "\t};"]),
			);
	}
	for (const binding of plan.functions) {
		lines.push(
			...docComment(binding.declaration.doc, "\t"),
			`\texport function ${binding.name}(${formatTsParameters(binding)}): ${formatTsResult(binding)};`,
		);
		if (binding.async !== undefined) {
			lines.push(
				...docComment(`Run ${binding.name} on a worker thread.`, "\t"),
				`\texport function ${binding.async}(${formatTsParameters(binding)}): Promise<${formatTsResult(binding)}>;`,
			);
		}
	}
	for (const constant of plan.constants) {
		lines.push(
			...docComment(constant.doc, "\t"),
			`\texport const ${constant.name}: ${constantType(constant)};`,
		);
	}
	lines.push("}");
	return lines;
}

type DeclaredLibraries = ReadonlyArray<{
	readonly name: string;
	readonly plan: BindingPlan;
}>;

function declarationBody(libraries: DeclaredLibraries): string {
	return libraries
		.flatMap((library, index) => [
			...(index === 0 ? [] : [""]),
			...moduleDeclaration(library.name, library.plan),
		])
		.join("\n");
}

/**
 * Ambient declarations for each library's `maligator:ffi/<name>` module, with the
 * header documentation, so editors and `tsc` resolve the imports. The header records
 * a digest of the declarations, which survives a formatter rewriting the file.
 */
export function generateDeclarations(libraries: DeclaredLibraries): string {
	const body = declarationBody(libraries);
	return [
		"// Generated by `maligator ffi types` from the libraries' headers. Do not edit.",
		`// Digest ${artifactDigest(body)}`,
		"",
		`${body}\n`,
	].join("\n");
}

/** Whether a file `generateDeclarations` wrote still declares `libraries`. */
export function declarationsCurrent(text: string, libraries: DeclaredLibraries): boolean {
	return (
		/^\/\/ Digest (\S+)$/m.exec(text)?.[1] === artifactDigest(declarationBody(libraries))
	);
}
