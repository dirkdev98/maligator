import type { BindingPlan, MappedConstant } from "./binding-plan.ts";
import { ffiModuleSpecifier } from "./binding-unit.ts";
import { formatTsParameters, formatTsResult, formatTsType } from "./inspect.ts";

function docComment(doc: string | undefined, indent: string): Array<string> {
	if (doc === undefined) return [];
	const lines = doc.replaceAll("*/", "*\\/").split("\n");
	return lines.length === 1
		? [`${indent}/** ${lines[0]} */`]
		: [
				`${indent}/**`,
				...lines.map((line) => `${indent} * ${line}`.trimEnd()),
				`${indent} */`,
			];
}

/** A literal type for a constant whose value the build already knows. */
function constantType(constant: MappedConstant): string {
	const known = constant.known;
	if (typeof known === "bigint") return `${known}n`;
	if (typeof known === "string") return JSON.stringify(known);
	if (typeof known === "number" && Number.isInteger(known)) return String(known);
	return formatTsType(constant.value);
}

function moduleDeclaration(library: string, plan: BindingPlan): Array<string> {
	const lines = [`declare module ${JSON.stringify(ffiModuleSpecifier(library))} {`];
	const records = [...plan.records.values()].sort((left, right) =>
		left.name < right.name ? -1 : left.name > right.name ? 1 : 0,
	);
	for (const record of records) {
		lines.push(
			...docComment(record.record.doc, "\t"),
			`\texport interface ${record.name} {`,
		);
		for (const field of record.fields) {
			lines.push(
				...docComment(field.doc, "\t\t"),
				`\t\t${field.name}: ${formatTsType(field.value)};`,
			);
		}
		lines.push("\t}");
	}
	for (const handle of plan.handles.values()) {
		lines.push(
			...docComment(handle.doc, "\t"),
			`\texport interface ${handle.name} {`,
			`\t\treadonly [Symbol.toStringTag]: ${JSON.stringify(handle.name)};`,
			`\t\t/** Close the handle${handle.destroy === undefined ? "" : `, releasing an owned resource with ${handle.destroy.name}`}. */`,
			"\t\t[Symbol.dispose](): void;",
		);
		for (const field of handle.fields) {
			lines.push(
				...docComment(field.doc, "\t\t"),
				`\t\treadonly ${field.name}: ${formatTsType(field.value)};`,
			);
		}
		lines.push("\t}");
	}
	for (const binding of plan.functions) {
		lines.push(
			...docComment(binding.declaration.doc, "\t"),
			`\texport function ${binding.name}(${formatTsParameters(binding)}): ${formatTsResult(binding)};`,
		);
	}
	for (const constant of plan.constants) {
		lines.push(
			...docComment(constant.doc, "\t"),
			`\texport const ${constant.name}: ${constantType(constant)};`,
		);
	}
	lines.push("}");
	return lines;
}

/**
 * Ambient declarations for each library's `maligator:ffi/<name>` module, with the
 * header documentation, so editors and `tsc` resolve the imports.
 */
export function generateDeclarations(
	libraries: ReadonlyArray<{ readonly name: string; readonly plan: BindingPlan }>,
): string {
	return `${[
		"// Generated by `maligator ffi types` from the libraries' headers. Do not edit.",
		"",
		...libraries.flatMap((library, index) => [
			...(index === 0 ? [] : [""]),
			...moduleDeclaration(library.name, library.plan),
		]),
	].join("\n")}\n`;
}
